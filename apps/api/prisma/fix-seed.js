const fs = require('fs');
let s = fs.readFileSync('seed.ts', 'utf8');

// Fix skill IDs: s1-s36
for (let i = 1; i <= 36; i++) {
  const uuid = 'c0000000-0000-0000-0000-' + String(i).padStart(12, '0');
  const re = new RegExp("'s" + i + "'", 'g');
  s = s.replace(re, "'" + uuid + "'");
}

// Fix candidate IDs
const candidateMap = {
  'c1111111-1111-1111-1111-111111111111': 'd1000000-0000-0000-0000-000000000001',
  'c2222222-2222-2222-2222-222222222222': 'd2000000-0000-0000-0000-000000000002',
  'c3333333-3333-3333-3333-333333333333': 'd3000000-0000-0000-0000-000000000003',
  'c4444444-4444-4444-4444-444444444444': 'd4000000-0000-0000-0000-000000000004',
  'c5555555-5555-5555-5555-555555555555': 'd5000000-0000-0000-0000-000000000005',
  'c6666666-6666-6666-6666-666666666666': 'd6000000-0000-0000-0000-000000000006',
  'c7777777-7777-7777-7777-777777777777': 'd7000000-0000-0000-0000-000000000007',
  'c8888888-8888-8888-8888-888888888888': 'd8000000-0000-0000-0000-000000000008',
  'c9999999-9999-9999-9999-999999999999': 'd9000000-0000-0000-0000-000000000009',
  'caaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa': 'da000000-0000-0000-0000-00000000000a',
};

for (const [old, rep] of Object.entries(candidateMap)) {
  const re = new RegExp(old.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
  s = s.replace(re, rep);
}

// Fix job IDs
const jobMap = {
  'j1111111-1111-1111-1111-111111111111': 'e1000000-0000-0000-0000-000000000001',
  'j2222222-2222-2222-2222-222222222222': 'e2000000-0000-0000-0000-000000000002',
  'j3333333-3333-3333-3333-333333333333': 'e3000000-0000-0000-0000-000000000003',
  'j4444444-4444-4444-4444-444444444444': 'e4000000-0000-0000-0000-000000000004',
  'j5555555-5555-5555-5555-555555555555': 'e5000000-0000-0000-0000-000000000005',
  'j6666666-6666-6666-6666-666666666666': 'e6000000-0000-0000-0000-000000000006',
};

for (const [old, rep] of Object.entries(jobMap)) {
  const re = new RegExp(old.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
  s = s.replace(re, rep);
}

fs.writeFileSync('seed.ts', s);
console.log('All UUIDs fixed');
